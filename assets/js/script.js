const STORAGE_KEY = 'joao-portfolio-language';
const state = {
    language: 'pt',
    activeProjectIndex: null,
    lastFocusedElement: null
};

function getInitialLanguage() {
    const savedLanguage = localStorage.getItem(STORAGE_KEY);

    if (savedLanguage === 'pt' || savedLanguage === 'en') {
        return savedLanguage;
    }

    return navigator.language && navigator.language.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

function escapeHtml(value) {
    return String(value)
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&#039;');
}

function applyStaticText(copy) {
    document.documentElement.lang = state.language === 'pt' ? 'pt-BR' : 'en';
    document.title = copy.documentTitle;

    const description = document.querySelector('meta[name="description"]');
    if (description) {
        description.setAttribute('content', copy.documentDescription);
    }

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.dataset.i18n;
        if (copy[key]) {
            element.textContent = copy[key];
        }
    });

    document.querySelectorAll('.lang-switch').forEach((switcher) => {
        switcher.setAttribute('aria-label', copy.languageToggleLabel);
    });

    document.querySelectorAll('[data-lang-option]').forEach((button) => {
        const isActive = button.dataset.langOption === state.language;
        button.classList.toggle('active', isActive);
        button.setAttribute('aria-pressed', String(isActive));
    });

    const menuToggle = document.querySelector('.mobile-menu-toggle');
    const menuClose = document.querySelector('.mobile-nav-close');
    const modalClose = document.querySelector('.modal-close');

    if (menuToggle) {
        menuToggle.setAttribute('aria-label', copy.openMenuLabel);
    }

    if (menuClose) {
        menuClose.setAttribute('aria-label', copy.closeMenuLabel);
    }

    if (modalClose) {
        modalClose.setAttribute('aria-label', copy.closeModalLabel);
    }
}

function createTags(tags) {
    return tags.map((tag) => `<span>${escapeHtml(tag)}</span>`).join('');
}

function renderProjects(copy) {
    const container = document.getElementById('projectsGrid');

    container.innerHTML = copy.projects.map((project, index) => {
        const blogLink = project.blog
            ? `<a class="button button-secondary" href="#blog">${escapeHtml(copy.blogButton)}</a>`
            : '';
        const accessLink = project.accessUrl
            ? `<a class="button button-primary" href="${escapeHtml(project.accessUrl)}" target="_blank" rel="noopener noreferrer">${escapeHtml(copy.accessButton)}</a>`
            : `<a class="button button-primary" href="#" data-placeholder-link>${escapeHtml(copy.accessButton)}</a>`;
        const projectActions = project.isComingSoon
            ? `
                        <button class="button button-primary button-disabled" type="button" disabled>${escapeHtml(copy.soonButton)}</button>
                        <button class="button button-secondary button-disabled" type="button" disabled>${escapeHtml(copy.detailsButton)}</button>`
            : `
                        ${accessLink}
                        <button class="button button-secondary" type="button" data-project-details="${index}">${escapeHtml(copy.detailsButton)}</button>
                        ${blogLink}`;

        return `
            <article class="project-card"${project.slug ? ` id="project-${escapeHtml(project.slug)}"` : ''}>
                <div class="project-visual ${escapeHtml(project.visualClass)}${project.image ? ' has-image' : ''}" data-visual-label="${escapeHtml(project.visualLabel)}" role="img" aria-label="${escapeHtml(project.title)} visual">
                    ${project.image ? `<img src="${escapeHtml(project.image)}" alt="${escapeHtml(project.title)} screenshot" loading="lazy">` : ''}
                </div>
                <div class="project-content">
                    <span class="project-type">${escapeHtml(project.type)}</span>
                    <h3>${escapeHtml(project.title)}</h3>
                    <p class="project-description">${escapeHtml(project.description)}</p>
                    <p class="project-role"><strong>${escapeHtml(copy.roleLabel)}:</strong> ${escapeHtml(project.role)}</p>
                    <div class="project-actions">
                        ${projectActions}
                    </div>
                </div>
            </article>
        `;
    }).join('');
}

function renderTimeline(copy) {
    const container = document.getElementById('timeline');

    container.innerHTML = copy.timeline.map((item) => `
        <article class="timeline-item">
            <h3>${escapeHtml(item.title)}</h3>
            <p>${escapeHtml(item.description)}</p>
        </article>
    `).join('');
}

function renderBlog(copy) {
    const container = document.getElementById('blogGrid');

    container.innerHTML = copy.blogPosts.map((post) => `
        <article class="blog-card">
            <span class="tag">${escapeHtml(post.category)}</span>
            <h3>${escapeHtml(post.title)}</h3>
            <p>${escapeHtml(post.description)}</p>
            <div class="blog-meta">
                <span class="date">${escapeHtml(post.date)}</span>
                <a href="#" data-placeholder-link>${escapeHtml(copy.blogRead)}</a>
            </div>
        </article>
    `).join('');
}

function renderAll() {
    const copy = COPY[state.language];

    applyStaticText(copy);
    renderProjects(copy);
    renderTimeline(copy);
    renderBlog(copy);

    if (state.activeProjectIndex !== null) {
        fillProjectModal(state.activeProjectIndex);
    }
}

function setLanguage(language, shouldPersist = true) {
    state.language = language;

    if (shouldPersist) {
        localStorage.setItem(STORAGE_KEY, language);
    }

    renderAll();
}

function fillProjectModal(index) {
    const copy = COPY[state.language];
    const project = copy.projects[index];

    if (!project) {
        return;
    }

    const modal = document.getElementById('projectModal');
    const modalNote = document.getElementById('modalNote');
    const systemsBlock = document.getElementById('modalSystemsBlock');
    const contributionsTitle = document.getElementById('modalContributionsTitle');
    const systemsTitle = document.getElementById('modalSystemsTitle');
    const modalActions = document.getElementById('modalActions');
    const modalAccess = document.getElementById('modalAccess');
    const modalCloseAction = document.getElementById('modalCloseAction');
    const highlights = project.details.highlights;
    const isCompact = Array.isArray(highlights);

    modal.classList.toggle('is-compact-modal', isCompact);
    document.getElementById('modalType').textContent = project.type;
    document.getElementById('modalTitle').textContent = project.title;
    document.getElementById('modalDescription').textContent = project.modalSummary || project.description;

    if (isCompact) {
        document.getElementById('modalMeta').innerHTML = createTags([`${copy.modalRoleLabel}: ${project.role}`]);
        contributionsTitle.textContent = copy.modalHighlightsTitle;
        document.getElementById('modalContributions').innerHTML = highlights
            .map((item) => `<li>${escapeHtml(item)}</li>`)
            .join('');
        document.getElementById('modalSystems').innerHTML = '';
        systemsBlock.hidden = true;
        modalActions.hidden = false;
        modalCloseAction.textContent = copy.modalCloseActionLabel;

        if (project.accessUrl) {
            modalAccess.textContent = copy.modalAccessLabel;
            modalAccess.href = project.accessUrl;
            modalAccess.target = '_blank';
            modalAccess.rel = 'noopener noreferrer';
            modalAccess.removeAttribute('data-placeholder-link');
            modalAccess.removeAttribute('data-modal-close');
        } else {
            modalAccess.textContent = copy.contactButton;
            modalAccess.href = '#contact';
            modalAccess.removeAttribute('target');
            modalAccess.removeAttribute('rel');
            modalAccess.removeAttribute('data-placeholder-link');
            modalAccess.setAttribute('data-modal-close', '');
        }

        if (project.modalNote) {
            modalNote.textContent = project.modalNote;
            modalNote.hidden = false;
        } else {
            modalNote.textContent = '';
            modalNote.hidden = true;
        }
        return;
    }

    document.getElementById('modalMeta').innerHTML = createTags([project.role, ...project.tags]);
    modalNote.textContent = '';
    modalNote.hidden = true;
    contributionsTitle.textContent = copy.modalContributionsTitle;
    systemsTitle.textContent = copy.modalSystemsTitle;
    systemsBlock.hidden = false;
    modalActions.hidden = true;
    document.getElementById('modalContributions').innerHTML = project.details.contributions
        .map((item) => `<li>${escapeHtml(item)}</li>`)
        .join('');
    document.getElementById('modalSystems').innerHTML = project.details.systems
        .map((item) => `<li>${escapeHtml(item)}</li>`)
        .join('');
}

function openProjectModal(index) {
    const modal = document.getElementById('projectModal');

    state.activeProjectIndex = Number(index);
    state.lastFocusedElement = document.activeElement;
    fillProjectModal(state.activeProjectIndex);
    modal.hidden = false;
    document.body.style.overflow = 'hidden';

    const closeButton = modal.querySelector('.modal-close');
    if (closeButton) {
        closeButton.focus();
    }
}

function closeProjectModal() {
    const modal = document.getElementById('projectModal');

    modal.hidden = true;
    document.body.style.overflow = '';
    state.activeProjectIndex = null;

    if (state.lastFocusedElement && typeof state.lastFocusedElement.focus === 'function') {
        state.lastFocusedElement.focus();
    }
}

function setupMobileMenu() {
    const menu = document.getElementById('mobileNav');
    const toggle = document.querySelector('.mobile-menu-toggle');
    const close = document.querySelector('.mobile-nav-close');

    function openMenu() {
        menu.hidden = false;
        toggle.setAttribute('aria-expanded', 'true');
    }

    function closeMenu() {
        menu.hidden = true;
        toggle.setAttribute('aria-expanded', 'false');
    }

    toggle.addEventListener('click', openMenu);
    close.addEventListener('click', closeMenu);

    menu.addEventListener('click', (event) => {
        if (event.target === menu || event.target.closest('a')) {
            closeMenu();
        }
    });
}

function setupActiveNavigation() {
    const sections = [...document.querySelectorAll('[data-section]')];
    const links = [...document.querySelectorAll('[data-nav-link]')];

    function setActive(id) {
        links.forEach((link) => {
            link.classList.toggle('active', link.getAttribute('href') === `#${id}`);
        });
    }

    if (!('IntersectionObserver' in window)) {
        setActive('intro');
        return;
    }

    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                setActive(entry.target.id);
            }
        });
    }, {
        rootMargin: '-35% 0px -55% 0px',
        threshold: 0
    });

    sections.forEach((section) => observer.observe(section));
}

